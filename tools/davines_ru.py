L = json.load(open('tools/altegio_live.json'))['goods']
plan, missing = {}, []
for k, g in L.items():
    if g['brand'] != 'Davines' or not g['price']: continue
    p = c.P.get(int(k))
    if not p: missing.append((k, g['title'])); continue
    name, vol = p[1], p[2]
    if name not in RU: missing.append((k, name)); continue
    line, desc = RU[name]
    v = vol.replace(' ml', ' мл').replace(' g', ' г') if vol else ''
    plan[k] = {'old': g['title'], 'new': ' '.join(x for x in ('Davines', line, desc, v) if x)}
json.dump(plan, open('tools/davines_rename_plan.json', 'w'), ensure_ascii=False, indent=1)
print(len(plan), 'planned; missing:', missing)
